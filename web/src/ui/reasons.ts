export function reasonText(reason?: string | null, fallback = 'No se pudo completar la acción.'): string {
  if (!reason) return fallback;
  if (R[reason]) return R[reason];
  for (const k of Object.keys(R)) if (reason.includes(k)) return R[k];
  return fallback + ' (' + reason + ')';
}
